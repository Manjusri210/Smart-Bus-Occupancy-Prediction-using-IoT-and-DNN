#!/usr/bin/env python3
"""
SmartBus AI — Synthetic Demonstration Dataset Generator
=======================================================
Generates realistic, physically-sound passenger occupancy time-series data
for training, validation, and dashboard demonstration.

NOTE: All records generated by this script are explicitly labelled as 'synthetic'.
Never represent synthetic data as real hardware observations.

Usage:
  python generate_demo_data.py --output ../data/synthetic_bus_trips.csv --trips 12
"""

import os
import argparse
import random
from pathlib import Path
import pandas as pd
import numpy as np

BUS_CAPACITY = 40


def simulate_bus_trip(
    trip_id: int,
    start_time_s: int,
    trip_type: str = "morning_peak",
    num_stops: int = 15,
    stop_interval_s: int = 45
) -> pd.DataFrame:
    """
    Simulates a single bus trip along a transit corridor with multiple stops.
    """
    records = []
    current_time = start_time_s
    entries = 0
    exits = 0
    passengers = 0

    # Rate multipliers depending on trip type
    if trip_type == "morning_peak":
        # Heavy boarding early, heavy alighting late, peaks near 30-38
        stop_board_weights = [random.randint(3, 7) for _ in range(num_stops // 2)] + [random.randint(0, 2) for _ in range(num_stops - num_stops // 2)]
        stop_alight_weights = [random.randint(0, 1) for _ in range(num_stops // 3)] + [random.randint(3, 8) for _ in range(num_stops - num_stops // 3)]
    elif trip_type == "evening_peak":
        # Heavy boarding late afternoon, high occupancy
        stop_board_weights = [random.randint(4, 8) for _ in range(num_stops // 2)] + [random.randint(1, 3) for _ in range(num_stops - num_stops // 2)]
        stop_alight_weights = [random.randint(0, 2) for _ in range(num_stops // 3)] + [random.randint(3, 7) for _ in range(num_stops - num_stops // 3)]
    elif trip_type == "off_peak":
        # Moderate flow, occupancy remains in 8-22 range
        stop_board_weights = [random.randint(1, 4) for _ in range(num_stops)]
        stop_alight_weights = [random.randint(1, 4) for _ in range(num_stops)]
    else:  # "night_low"
        # Light flow, occupancy remains low (< 12)
        stop_board_weights = [random.randint(0, 2) for _ in range(num_stops)]
        stop_alight_weights = [random.randint(0, 2) for _ in range(num_stops)]

    for stop_idx in range(num_stops):
        # Time driving to next stop with periodic sensor readings every 5-10 seconds
        segment_seconds = stop_interval_s + random.randint(-5, 10)
        num_ticks = max(3, segment_seconds // 5)

        for _ in range(num_ticks):
            current_time += 5
            pct = round((passengers / float(BUS_CAPACITY)) * 100.0, 1)
            records.append({
                "time_s": current_time,
                "entries": entries,
                "exits": exits,
                "passengers": passengers,
                "occupancy_pct": pct,
                "trip_id": trip_id,
                "trip_type": trip_type,
                "source": "synthetic"
            })

        # Bus arrives at stop: passengers board and alight
        b_target = stop_board_weights[stop_idx]
        a_target = stop_alight_weights[stop_idx]

        # Alight first (cannot exceed current passengers)
        actual_alight = min(passengers, a_target)
        exits += actual_alight
        passengers -= actual_alight

        # Board passengers (cannot exceed remaining bus capacity)
        remaining_capacity = BUS_CAPACITY - passengers
        actual_board = min(remaining_capacity, b_target)
        entries += actual_board
        passengers += actual_board

        # Record stop state
        current_time += 15  # Stop dwell time
        pct = round((passengers / float(BUS_CAPACITY)) * 100.0, 1)
        records.append({
            "time_s": current_time,
            "entries": entries,
            "exits": exits,
            "passengers": passengers,
            "occupancy_pct": pct,
            "trip_id": trip_id,
            "trip_type": trip_type,
            "source": "synthetic"
        })

    # End of line: remaining passengers alight
    if passengers > 0:
        current_time += 10
        exits += passengers
        passengers = 0
        records.append({
            "time_s": current_time,
            "entries": entries,
            "exits": exits,
            "passengers": 0,
            "occupancy_pct": 0.0,
            "trip_id": trip_id,
            "trip_type": trip_type,
            "source": "synthetic"
        })

    return pd.DataFrame(records)


def generate_full_synthetic_dataset(num_trips: int = 15, output_path: str = None) -> pd.DataFrame:
    """
    Generates multi-trip synthetic dataset covering morning, midday, evening, and night patterns.
    """
    random.seed(42)
    np.random.seed(42)

    trip_types = [
        "morning_peak", "morning_peak", "morning_peak",
        "off_peak", "off_peak", "off_peak",
        "evening_peak", "evening_peak", "evening_peak", "evening_peak",
        "night_low", "night_low"
    ]

    all_trips = []
    global_time = 0

    for i in range(num_trips):
        t_type = trip_types[i % len(trip_types)]
        trip_df = simulate_bus_trip(
            trip_id=i + 1,
            start_time_s=global_time,
            trip_type=t_type,
            num_stops=random.randint(12, 18),
            stop_interval_s=random.randint(35, 60)
        )
        all_trips.append(trip_df)
        global_time = int(trip_df["time_s"].max()) + random.randint(120, 300)

    combined_df = pd.concat(all_trips, ignore_index=True)

    if output_path:
        out = Path(output_path)
        out.parent.mkdir(parents=True, exist_ok=True)
        # Select standard CSV columns with source
        cols = ["time_s", "entries", "exits", "passengers", "occupancy_pct", "source"]
        combined_df[cols].to_csv(out, index=False)
        print(f"[+] Successfully generated synthetic dataset with {len(combined_df)} records across {num_trips} trips.")
        print(f"[+] Saved to: {out.resolve()}")
        print(f"[+] Peak passengers: {combined_df['passengers'].max()}/40 ({(combined_df['passengers'].max()/40)*100:.1f}%)")
        print(f"[+] Mean passengers: {combined_df['passengers'].mean():.1f}")

    return combined_df


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="SmartBus AI Synthetic Data Generator")
    parser.add_argument("--output", default="../data/synthetic_bus_trips.csv", help="Output CSV path")
    parser.add_argument("--trips", type=int, default=16, help="Number of trips to simulate")
    args = parser.parse_args()

    generate_full_synthetic_dataset(num_trips=args.trips, output_path=args.output)
